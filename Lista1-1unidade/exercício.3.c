/*
 * Este programa demonstra o uso de comentários em C.
 * Utiliza comentários de múltiplas linhas e de linha única.
 *
 */

#include <stdio.h> // Biblioteca que será usada no printf

int main() // a função do programa
{
    // Declaração da variável inteira
    int idade = 12;

    /*
     * mostra uma mensagem no console.
     * O especificador %d serve para imprimir o número inteiro.
     */

    printf("Minha idade é: %d\n", idade);

    return 0; // Finaliza o programa
}